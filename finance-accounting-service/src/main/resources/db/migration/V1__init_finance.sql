-- V1__init_finance.sql
-- Initial Finance Accounting schema

-- Fiscal Years
CREATE TABLE fiscal_years (
    id BINARY(16) NOT NULL,
    year INT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    description VARCHAR(500),
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    closed_at DATE,
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_fiscal_year_year (year)
);

-- Fiscal Periods
CREATE TABLE fiscal_periods (
    id BINARY(16) NOT NULL,
    fiscal_year_id BINARY(16) NOT NULL,
    period_number INT NOT NULL,
    name VARCHAR(50),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    locked_at DATE,
    locked_by VARCHAR(200),
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    closed_at DATE,
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_fiscal_period_year_number (fiscal_year_id, period_number),
    FOREIGN KEY (fiscal_year_id) REFERENCES fiscal_years(id)
);

-- Chart of Accounts
CREATE TABLE chart_of_accounts (
    id BINARY(16) NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(500),
    account_type VARCHAR(20) NOT NULL,
    account_nature VARCHAR(10) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_detail BOOLEAN NOT NULL DEFAULT TRUE,
    level INT NOT NULL,
    parent_id BINARY(16),
    fiscal_year_id BINARY(16) NOT NULL,
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_chart_of_accounts_code (code),
    UNIQUE KEY uk_chart_of_accounts_name (name),
    FOREIGN KEY (parent_id) REFERENCES chart_of_accounts(id),
    FOREIGN KEY (fiscal_year_id) REFERENCES fiscal_years(id)
);

-- Cost Centers
CREATE TABLE cost_centers (
    id BINARY(16) NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(500),
    cost_center_type VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    parent_id BINARY(16),
    manager_id BINARY(16),
    budget_amount DECIMAL(19,2),
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_cost_center_code (code),
    UNIQUE KEY uk_cost_center_name (name),
    FOREIGN KEY (parent_id) REFERENCES cost_centers(id),
    FOREIGN KEY (manager_id) REFERENCES employees(id)
);

-- Employees
CREATE TABLE employees (
    id BINARY(16) NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(200) NOT NULL,
    phone VARCHAR(20),
    hire_date DATE,
    termination_date DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_employee_code (code),
    UNIQUE KEY uk_employee_email (email)
);

-- Journal Entries
CREATE TABLE journal_entries (
    id BINARY(16) NOT NULL,
    reference VARCHAR(50) NOT NULL,
    entry_date DATE NOT NULL,
    fiscal_period_id BINARY(16) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    total_debit DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    total_credit DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    is_reversed BOOLEAN NOT NULL DEFAULT FALSE,
    reversed_entry_id BINARY(16),
    reversal_reason VARCHAR(500),
    posted_at DATETIME,
    posted_by VARCHAR(200),
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_journal_entry_reference (reference, fiscal_period_id),
    FOREIGN KEY (fiscal_period_id) REFERENCES fiscal_periods(id),
    FOREIGN KEY (reversed_entry_id) REFERENCES journal_entries(id),
    INDEX idx_journal_entry_fiscal_period (fiscal_period_id),
    INDEX idx_journal_entry_entry_date (entry_date),
    INDEX idx_journal_entry_status (status)
);

-- Journal Entry Lines
CREATE TABLE journal_entry_lines (
    id BINARY(16) NOT NULL,
    journal_entry_id BINARY(16) NOT NULL,
    account_id BINARY(16) NOT NULL,
    cost_center_id BINARY(16),
    line_number INT NOT NULL,
    description VARCHAR(500),
    debit_amount DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    credit_amount DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id) ON DELETE CASCADE,
    FOREIGN KEY (account_id) REFERENCES chart_of_accounts(id),
    FOREIGN KEY (cost_center_id) REFERENCES cost_centers(id),
    INDEX idx_journal_entry_line_account (account_id),
    INDEX idx_journal_entry_line_cost_center (cost_center_id)
);

-- GL Entries
CREATE TABLE gl_entries (
    id BINARY(16) NOT NULL,
    journal_entry_id BINARY(16) NOT NULL,
    account_id BINARY(16) NOT NULL,
    cost_center_id BINARY(16),
    fiscal_period_id BINARY(16) NOT NULL,
    entry_date DATE NOT NULL,
    entry_type VARCHAR(10) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    running_balance DECIMAL(19,2),
    description VARCHAR(500),
    created_at DATETIME NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id),
    FOREIGN KEY (account_id) REFERENCES chart_of_accounts(id),
    FOREIGN KEY (cost_center_id) REFERENCES cost_centers(id),
    FOREIGN KEY (fiscal_period_id) REFERENCES fiscal_periods(id),
    INDEX idx_gl_entry_account (account_id),
    INDEX idx_gl_entry_fiscal_period (fiscal_period_id),
    INDEX idx_gl_entry_entry_date (entry_date),
    INDEX idx_gl_entry_journal_entry (journal_entry_id)
);

-- Reversal Entries
CREATE TABLE reversal_entries (
    id BINARY(16) NOT NULL,
    original_entry_id BINARY(16) NOT NULL,
    reversal_entry_id BINARY(16) NOT NULL,
    reversal_date DATE NOT NULL,
    reason VARCHAR(500),
    reversed_by VARCHAR(200),
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (original_entry_id) REFERENCES journal_entries(id),
    FOREIGN KEY (reversal_entry_id) REFERENCES journal_entries(id),
    INDEX idx_reversal_entry_original (original_entry_id),
    INDEX idx_reversal_entry_reversal_date (reversal_date)
);

-- Currencies
CREATE TABLE currencies (
    id BINARY(16) NOT NULL,
    code VARCHAR(3) NOT NULL,
    iso_code VARCHAR(3) NOT NULL,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(5) NOT NULL,
    decimal_places INT NOT NULL DEFAULT 2,
    is_base_currency BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_currency_code (code),
    UNIQUE KEY uk_currency_iso_code (iso_code)
);

-- Bank Accounts
CREATE TABLE bank_accounts (
    id BINARY(16) NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    bank_code VARCHAR(10) NOT NULL,
    branch_code VARCHAR(10) NOT NULL,
    account_number VARCHAR(20) NOT NULL,
    account_digit VARCHAR(2),
    account_type VARCHAR(20) NOT NULL,
    currency_id BINARY(16) NOT NULL,
    gl_account_id BINARY(16) NOT NULL,
    initial_balance DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    current_balance DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    allows_multiple_currencies BOOLEAN NOT NULL DEFAULT FALSE,
    notes VARCHAR(500),
    created_at DATE NOT NULL,
    updated_at DATE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_bank_account_code (code),
    UNIQUE KEY uk_bank_account_number (bank_code, branch_code, account_number),
    FOREIGN KEY (currency_id) REFERENCES currencies(id),
    FOREIGN KEY (gl_account_id) REFERENCES chart_of_accounts(id)
);

-- Bank Statements
CREATE TABLE bank_statements (
    id BINARY(16) NOT NULL,
    bank_account_id BINARY(16) NOT NULL,
    statement_date DATE NOT NULL,
    statement_number VARCHAR(50),
    opening_balance DECIMAL(19,2) NOT NULL,
    closing_balance DECIMAL(19,2) NOT NULL,
    total_debits DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    total_credits DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'IMPORTED',
    imported_at DATETIME,
    imported_by VARCHAR(200),
    reconciled_at DATETIME,
    reconciled_by VARCHAR(200),
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_bank_statement_account_period (bank_account_id, statement_date),
    FOREIGN KEY (bank_account_id) REFERENCES bank_accounts(id),
    INDEX idx_bank_statement_account (bank_account_id),
    INDEX idx_bank_statement_date (statement_date),
    INDEX idx_bank_statement_status (status)
);

-- Bank Statement Lines
CREATE TABLE bank_statement_lines (
    id BINARY(16) NOT NULL,
    bank_statement_id BINARY(16) NOT NULL,
    line_number INT NOT NULL,
    transaction_date DATE NOT NULL,
    value_date DATE,
    transaction_type VARCHAR(10) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    balance_after DECIMAL(19,2),
    description VARCHAR(200),
    reference VARCHAR(200),
    counterpart_name VARCHAR(200),
    counterpart_document VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'UNRECONCILED',
    reconciliation_id BINARY(16),
    gl_entry_id BINARY(16),
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (bank_statement_id) REFERENCES bank_statements(id) ON DELETE CASCADE,
    FOREIGN KEY (reconciliation_id) REFERENCES reconciliations(id),
    FOREIGN KEY (gl_entry_id) REFERENCES gl_entries(id),
    INDEX idx_bank_stmt_line_statement (bank_statement_id),
    INDEX idx_bank_stmt_line_date (transaction_date),
    INDEX idx_bank_stmt_line_status (status),
    INDEX idx_bank_stmt_line_reconciliation (reconciliation_id)
);

-- Reconciliations
CREATE TABLE reconciliations (
    id BINARY(16) NOT NULL,
    bank_account_id BINARY(16) NOT NULL,
    reconciliation_date DATE NOT NULL,
    reference VARCHAR(50),
    book_balance DECIMAL(19,2) NOT NULL,
    bank_balance DECIMAL(19,2) NOT NULL,
    difference DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    completed_at DATETIME,
    completed_by VARCHAR(200),
    notes VARCHAR(1000),
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (bank_account_id) REFERENCES bank_accounts(id),
    INDEX idx_reconciliation_bank_account (bank_account_id),
    INDEX idx_reconciliation_date (reconciliation_date),
    INDEX idx_reconciliation_status (status)
);

-- Reconciliation Items
CREATE TABLE reconciliation_items (
    id BINARY(16) NOT NULL,
    reconciliation_id BINARY(16) NOT NULL,
    bank_statement_line_id BINARY(16),
    gl_entry_id BINARY(16),
    item_type VARCHAR(20) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    notes VARCHAR(500),
    matched_at DATETIME,
    matched_by VARCHAR(200),
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (reconciliation_id) REFERENCES reconciliations(id) ON DELETE CASCADE,
    FOREIGN KEY (bank_statement_line_id) REFERENCES bank_statement_lines(id),
    FOREIGN KEY (gl_entry_id) REFERENCES gl_entries(id),
    INDEX idx_reconciliation_item_reconciliation (reconciliation_id),
    INDEX idx_reconciliation_item_bank_stmt_line (bank_statement_line_id),
    INDEX idx_reconciliation_item_gl_entry (gl_entry_id),
    INDEX idx_reconciliation_item_status (status)
);

