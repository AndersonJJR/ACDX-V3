    posted_by VARCHAR(200),
    depreciation_entry_id BINARY(16),
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (asset_id) REFERENCES assets(id) ON DELETE CASCADE,
    FOREIGN KEY (fiscal_period_id) REFERENCES fiscal_periods(id),
    FOREIGN KEY (depreciation_entry_id) REFERENCES depreciation_entries(id),
    INDEX idx_depr_schedule_asset (asset_id),
    INDEX idx_depr_schedule_fiscal_period (fiscal_period_id),
    INDEX idx_depr_schedule_status (status)
);

