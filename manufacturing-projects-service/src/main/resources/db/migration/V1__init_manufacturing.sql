    version_lock BIGINT DEFAULT 0,
    FOREIGN KEY (bom_id) REFERENCES bom(id) ON DELETE CASCADE,
    INDEX idx_bom_operation_bom (bom_id),
    INDEX idx_bom_operation_workcenter (work_center_id),
    INDEX idx_bom_operation_sequence (sequence)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

