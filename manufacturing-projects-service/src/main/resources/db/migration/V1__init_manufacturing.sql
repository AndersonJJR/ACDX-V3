-- Initial manufacturing schema for MySQL

-- BOM Tables
CREATE TABLE bom (
    id CHAR(36) NOT NULL PRIMARY KEY,
    product_id CHAR(36) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    version VARCHAR(50),
    description VARCHAR(500),
    base_quantity DECIMAL(19,6) DEFAULT 1.000000,
    scrap_percentage DECIMAL(5,2) DEFAULT 0.00,
    is_phantom BOOLEAN DEFAULT FALSE,
    effective_from DATETIME,
    effective_to DATETIME,
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    version_lock BIGINT DEFAULT 0,
    INDEX idx_bom_product (product_id),
    INDEX idx_bom_status (status),
    INDEX idx_bom_type (type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE bom_item (
    id CHAR(36) NOT NULL PRIMARY KEY,
    bom_id CHAR(36) NOT NULL,
    component_id CHAR(36) NOT NULL,
    component_type VARCHAR(50),
    quantity DECIMAL(19,6) NOT NULL,
    scrap_percentage DECIMAL(5,2) DEFAULT 0.00,
    position INT DEFAULT 0,
    unit_of_measure VARCHAR(20),
    is_phantom BOOLEAN DEFAULT FALSE,
    is_optional BOOLEAN DEFAULT FALSE,
    reference_designator VARCHAR(100),
    find_number VARCHAR(50),
    notes VARCHAR(1000),
    effective_from DATETIME,
    effective_to DATETIME,
    created_at DATETIME NOT NULL,
    updated_at DATETIME,
    version_lock BIGINT DEFAULT 0,
    FOREIGN KEY (bom_id) REFERENCES bom(id) ON DELETE CASCADE,
    INDEX idx_bom_item_bom (bom_id),
    INDEX idx_bom_item_component (component_id),
    INDEX idx_bom_item_position (position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE bom_operation (
    id CHAR(36) NOT NULL PRIMARY KEY,
    bom_id CHAR(36) NOT NULL,
    sequence INT NOT NULL,
    work_center_id CHAR(36),
    work_station_id CHAR(36),
    operation_name VARCHAR(200),
    description VARCHAR(1000),
    setup_time_minutes DECIMAL(10,2) DEFAULT 0.00,
    run_time_minutes DECIMAL(10,2) DEFAULT 0.00,
    queue_time_minutes DECIMAL(10,2) DEFAULT 0.00,
    move_time_minutes DECIMAL(10,2) DEFAULT 0.00,
