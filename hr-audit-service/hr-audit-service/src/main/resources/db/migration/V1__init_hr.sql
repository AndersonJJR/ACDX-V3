    device_id VARCHAR(100),
    ip_address VARCHAR(45),
    is_manual_adjustment BOOLEAN NOT NULL DEFAULT FALSE,
    adjustment_reason VARCHAR(500),
    adjusted_by BIGINT,
    adjusted_at TIMESTAMP NULL,
