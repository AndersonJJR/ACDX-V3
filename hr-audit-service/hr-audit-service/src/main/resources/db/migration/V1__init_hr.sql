-- Initial HR schema for ERP Brazil

-- Employee table
CREATE TABLE employee (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL UNIQUE,
    company_id BIGINT NOT NULL,
    employee_number VARCHAR(20) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    rg VARCHAR(20),
    birth_date DATE NOT NULL,
    gender ENUM('M', 'F', 'O') NOT NULL,
    marital_status ENUM('SINGLE', 'MARRIED', 'DIVORCED', 'WIDOWED', 'STABLE_UNION') NOT NULL,
    nationality VARCHAR(50) DEFAULT 'BRASILEIRA',
    naturalness VARCHAR(100),
    mother_name VARCHAR(255),
    father_name VARCHAR(255),
    email VARCHAR(255),
    personal_phone VARCHAR(20),
    corporate_phone VARCHAR(20),
    address_cep VARCHAR(10),
    address_street VARCHAR(255),
    address_number VARCHAR(20),
    address_complement VARCHAR(100),
    address_neighborhood VARCHAR(100),
    address_city VARCHAR(100),
    address_state VARCHAR(2),
    address_country VARCHAR(50) DEFAULT 'BRASIL',
    bank_code VARCHAR(3),
    bank_branch VARCHAR(10),
    bank_account VARCHAR(20),
    bank_account_type ENUM('CHECKING', 'SAVINGS'),
    pix_key VARCHAR(100),
    emergency_contact_name VARCHAR(255),
    emergency_contact_phone VARCHAR(20),
    emergency_contact_relationship VARCHAR(50),
    profile_photo_url VARCHAR(500),
    status ENUM('ACTIVE', 'INACTIVE', 'ON_LEAVE', 'TERMINATED', 'SUSPENDED') NOT NULL DEFAULT 'ACTIVE',
    hire_date DATE NOT NULL,
    termination_date DATE,
    termination_reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_employee_cpf (cpf),
    UNIQUE KEY uk_employee_number_company (employee_number, company_id),
    INDEX idx_employee_company (company_id),
    INDEX idx_employee_status (status),
    INDEX idx_employee_hire_date (hire_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Employment Contract table
CREATE TABLE employment_contract (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL UNIQUE,
    employee_id BIGINT NOT NULL,
    contract_type ENUM('CLT_INDEFINITE', 'CLT_FIXED_TERM', 'CLT_TEMPORARY', 'APPRENTICE', 'INTERNSHIP', 'STATUTORY', 'COOPERATIVE') NOT NULL,
    work_journey ENUM('FULL_TIME', 'PART_TIME_MORNING', 'PART_TIME_AFTERNOON', 'PART_TIME_NIGHT', 'SHIFT_12X36', 'SHIFT_6X1', 'CUSTOM') NOT NULL,
    weekly_hours DECIMAL(4,2) NOT NULL DEFAULT 44.00,
    daily_hours DECIMAL(4,2) NOT NULL DEFAULT 8.00,
    salary_base DECIMAL(12,2) NOT NULL,
    salary_hourly DECIMAL(10,4) GENERATED ALWAYS AS (salary_base / (weekly_hours * 52 / 12 / 220)) STORED,
    position_title VARCHAR(150) NOT NULL,
    position_cbo VARCHAR(10),
    department_id BIGINT,
    cost_center_id BIGINT,
    reporting_to_id BIGINT,
    work_location ENUM('ONSITE', 'REMOTE', 'HYBRID') NOT NULL DEFAULT 'ONSITE',
    work_city VARCHAR(100),
    work_state VARCHAR(2),
    union_id BIGINT,
    collective_agreement_id BIGINT,
    probation_end_date DATE,
    contract_start_date DATE NOT NULL,
    contract_end_date DATE,
    renewal_count INT DEFAULT 0,
    fgts_opt_in BOOLEAN NOT NULL DEFAULT TRUE,
    fgts_account VARCHAR(30),
    benefit_transport_voucher BOOLEAN NOT NULL DEFAULT TRUE,
    benefit_meal_voucher BOOLEAN NOT NULL DEFAULT TRUE,
    benefit_health_insurance BOOLEAN NOT NULL DEFAULT FALSE,
    benefit_dental_insurance BOOLEAN NOT NULL DEFAULT FALSE,
    benefit_life_insurance BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    FOREIGN KEY (employee_id) REFERENCES employee(id) ON DELETE CASCADE,
    INDEX idx_contract_employee (employee_id),
    INDEX idx_contract_dates (contract_start_date, contract_end_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Time Record table (Ponto Eletrônico)
CREATE TABLE time_record (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL UNIQUE,
    employee_id BIGINT NOT NULL,
    record_date DATE NOT NULL,
