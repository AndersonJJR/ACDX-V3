-- Leave Balance table
CREATE TABLE leave_balance (
    id BIGINT NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL UNIQUE,
    employee_id BIGINT NOT NULL,
    leave_type_id BIGINT NOT NULL,
    reference_year SMALLINT NOT NULL,
    accrued_days DECIMAL(5,2) NOT NULL DEFAULT 0,
    used_days DECIMAL(5,2) NOT NULL DEFAULT 0,
    pending_days DECIMAL(5,2) NOT NULL DEFAULT 0,
    carried_over_days DECIMAL(5,2) NOT NULL DEFAULT 0,
    expired_days DECIMAL(5,2) NOT NULL DEFAULT 0,
    available_days DECIMAL(5,2) GENERATED ALWAYS AS (accrued_days + carried_over_days - used_days - pending_days - expired_days) STORED,
