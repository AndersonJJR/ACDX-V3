    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (employee_id) REFERENCES employee(id) ON DELETE CASCADE,
    FOREIGN KEY (leave_type_id) REFERENCES leave_type(id) ON DELETE CASCADE,
    UNIQUE KEY uk_leave_balance_employee_type_year (employee_id, leave_type_id, reference_year),
    INDEX idx_leave_balance_employee_year (employee_id, reference_year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

